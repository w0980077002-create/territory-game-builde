// Execute the real Edge handler with synthetic credentials and a stub service RPC.
import assert from 'node:assert/strict';
import { createHmac, webcrypto } from 'node:crypto';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const calls = [];
const player = '10000000-0000-4000-8000-000000000001';
const operation = '20000000-0000-4000-8000-000000000001';
const fakeDb = { rpc: async (name, args) => {
 calls.push({ name, args });
 if (name === 'territory_admin_credential_v2') return {data:{version:1,salt:'00'.repeat(16),verifier:'00'.repeat(32)},error:null};
 if (name === 'territory_runes_admin_status_v1') return {data:{playerId:args.p_player,owned:[]},error:null};
 if (name === 'territory_runes_admin_set_level_v1') return {data:{playerId:args.p_player,runeId:args.p_rune,level:args.p_level,operationId:args.p_operation,previousLevel:0},error:null};
 throw Error(`Unexpected RPC: ${name}`);
}};
const source = readFileSync('supabase/functions/admin-api/index.ts','utf8').replace(/^import .*?;\s*/,'');
const js = ts.transpile(source,{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.None});
let serve;
vm.runInNewContext(js,{createClient:()=>fakeDb,Deno:{env:{get:()=> 'synthetic-service-key'},serve:fn=>{serve=fn}},crypto:webcrypto,TextEncoder,Request,Response,console});
const expiration=String(Date.now()+60000);
const sig=createHmac('sha256','synthetic-service-key:admin').update(expiration).digest('hex');
const token=`${expiration}.${sig}`;
const call=body=>serve(new Request('http://fixture/',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(body)}));
const payload={action:'runes_set_level',playerId:player,runeId:'shield_wall_r1',level:2,reason:'fixture grant',requestId:operation};
let response=await call({...payload,token:'ordinary-player-jwt'});
assert.equal(response.status,401);
assert.equal(calls.some(c=>c.name==='territory_runes_admin_set_level_v1'),false);
response=await call({...payload,token});
assert.equal(response.status,200);
assert.deepEqual(await response.json(),{playerId:player,runeId:'shield_wall_r1',level:2,operationId:operation,previousLevel:0});
const grant=calls.find(c=>c.name==='territory_runes_admin_set_level_v1');
assert.equal(grant.args.p_operation,operation);
response=await call({...payload,token,level:4});
assert.equal(response.status,400);
assert.equal(calls.filter(c=>c.name==='territory_runes_admin_set_level_v1').length,1);
response=await call({action:'runes_player',playerId:player,token});
assert.equal(response.status,200);
assert.equal((await response.json()).playerId,player);
console.log('Admin Edge handler: synthetic owner session, player denial, input validation and service RPC PASS');
