/** Isolated PostgreSQL trade tests. Never connects to production. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const db = new PGlite();
const A='10000000-0000-4000-8000-000000000001', B='10000000-0000-4000-8000-000000000002', C='10000000-0000-4000-8000-000000000003';
let counter=0;
const op=()=>`20000000-0000-4000-8000-${String(++counter).padStart(12,'0')}`;
const q=async(sql,args=[]) => (await db.query(sql,args)).rows;
const as=async(id)=>q("SELECT set_config('request.jwt.claim.sub',$1,false)",[id || '']);
const trade=async(action,operation,item=null,listing=null,price=null)=>(await q('SELECT public.territory_auction_trade_v1($1,$2,$3,$4,$5) AS r',[action,operation,item,listing,price]))[0].r;
const overview=async(search='',rarity='',sort='newest')=>(await q('SELECT public.territory_auction_overview_v1(50,$1,$2,$3) AS r',[search,rarity,sort]))[0].r;
try {
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE SCHEMA auth;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    CREATE TABLE players(id uuid PRIMARY KEY,display_name text,banned boolean DEFAULT false);
    CREATE TABLE territory_release_flags_v1(id integer PRIMARY KEY);
    INSERT INTO territory_release_flags_v1 VALUES(1);
    CREATE TABLE territory_crafted_items_v1(item_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),player_id uuid REFERENCES players(id),item_output jsonb,created_at timestamptz DEFAULT now());
    CREATE TABLE territory_wallet_v1(player_id uuid PRIMARY KEY REFERENCES players(id),gold bigint CHECK(gold BETWEEN 0 AND 2147483647),verified boolean DEFAULT false,updated_at timestamptz DEFAULT now());`);
  await db.exec(readFileSync(new URL('../supabase/staged/territory_stage5_auction.sql',import.meta.url),'utf8'));
  for(const id of [A,B,C]) await q('INSERT INTO players(id,display_name) VALUES($1,$2)',[id,id===A?'Seller':'Buyer']);
  await q('INSERT INTO territory_wallet_v1(player_id,gold,verified) VALUES($1,1000,true),($2,1000,true),($3,0,false)',[A,B,C]);
  const item=(await q(`INSERT INTO territory_crafted_items_v1(player_id,item_output) VALUES($1,'{"name":"Sword","rarity":"rare"}') RETURNING item_id`,[A]))[0].item_id;
  await as(A);
  assert.equal((await overview()).enabled,false);
  await assert.rejects(trade('list',op(),item,null,101),/auction_not_enabled/);
  await q('UPDATE territory_release_flags_v1 SET auction_enabled=true');
  const listOp=op(), listed=await trade('list',listOp,item,null,101);
  assert.deepEqual(await trade('list',listOp,item,null,101),listed,'list retry stable');
  await assert.rejects(trade('list',listOp,item,null,102),/operation_id_reused/);
  await assert.rejects(trade('list',op(),item,null,100),/item_not_available/);
  assert.equal((await overview()).items.length,0,'escrow hides inventory item');
  assert.equal((await overview('sWoRd','rare')).lots.length,1);
  assert.equal((await overview('Sword','epic')).lots.length,0);
  assert.equal((await overview('nothing')).lots.length,0);
  await assert.rejects(trade('buy',op(),null,listed.listing_id),/self_trade_forbidden/);
  await as(B);
  await assert.rejects(trade('cancel',op(),null,listed.listing_id),/not_listing_owner/);
  const buyOp=op(), bought=await trade('buy',buyOp,null,listed.listing_id);
  assert.equal(bought.fee_gold,11,'10% rounds upward');
  assert.equal(bought.seller_receives,90);
  assert.deepEqual(await trade('buy',buyOp,null,listed.listing_id),bought);
  assert.equal((await q('SELECT gold FROM territory_wallet_v1 WHERE player_id=$1',[A]))[0].gold,1090);
  assert.equal((await q('SELECT gold FROM territory_wallet_v1 WHERE player_id=$1',[B]))[0].gold,899);
  assert.equal((await q('SELECT fees_gold FROM territory_auction_treasury_v1'))[0].fees_gold,11);
  assert.equal((await overview()).history[0].role,'buyer');
  assert.equal((await overview()).items[0].item_id,item,'bought item belongs to buyer');
  await assert.rejects(trade('buy',op(),null,listed.listing_id),/listing_not_open/);
  const relisted=await trade('list',op(),item,null,60);
  const cancelOp=op(), cancelled=await trade('cancel',cancelOp,null,relisted.listing_id);
  assert.deepEqual(await trade('cancel',cancelOp,null,relisted.listing_id),cancelled);
  assert.equal((await overview()).items.length,1,'cancel restores item once');
  const again=await trade('list',op(),item,null,60);
  await as(C);
  await assert.rejects(trade('buy',op(),null,again.listing_id),/wallet_not_verified/);
  await q('UPDATE territory_wallet_v1 SET verified=true WHERE player_id=$1',[C]);
  await assert.rejects(trade('buy',op(),null,again.listing_id),/insufficient_gold/);
  await as(A);
  await q('UPDATE territory_wallet_v1 SET gold=2147483647 WHERE player_id=$1',[B]);
  await assert.rejects(trade('buy',op(),null,again.listing_id),/seller_wallet_overflow/);
  assert.equal((await q('SELECT player_id FROM territory_crafted_items_v1 WHERE item_id=$1',[item]))[0].player_id,B,'failed trade preserves ownership');
  assert.equal((await overview()).history[0].role,'seller');
  await as(null);
  await assert.rejects(overview(),/not_authenticated/);
  await q('SET ROLE authenticated');
  await assert.rejects(q('SELECT * FROM territory_auction_listings_v1'),/permission denied/);
  console.log('Auction SQL PASS: disabled gate, escrow, list/buy/cancel/replay, ownership, fee conservation, history, search, account ACL, insufficient funds, overflow rollback. Multi-connection lock stress remains a release check.');
} finally { await db.close(); }
