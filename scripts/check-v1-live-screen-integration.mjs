assert.match(progression,/latest\.enabled \? latest : null/,'Only show when explicitly enabled');
assert.match(progression,/readPending\(\)/,'Read durable pending request before any action');
assert.match(progression,/api\.resume\(\)/,'Resume same operation ID');
