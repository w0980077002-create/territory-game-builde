import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const sql = readFileSync('supabase/migrations/20261017_fair_arena_matchmaking.sql', 'utf8');
assert.match(sql, /CREATE OR REPLACE FUNCTION public\.arena_match_compatible/, 'Server match policy missing');
assert.match(sql, /CREATE OR REPLACE FUNCTION public\.arena_join\(p_mode text\)/, 'Actual join RPC must enforce matching');
assert.match(sql, /NOT EXISTS \([\s\S]*?NOT public\.arena_match_compatible\(/, 'Every other real player in lobby must be compatible');
assert.match(sql, /AND NOT ap\.is_bot/, 'Compare against real opponents, not filler bots');
for (const field of ['v_pl.level', 'v_pl.max_hp', 'v_pl.attack', 'v_pl.defense', 'v_pl.arena_rating',
  'ap.level', 'ap.max_hp', 'ap.attack', 'ap.defense', 'ap.rating']) {
  assert(sql.includes(field), 'Missing secure matchup comparison: ' + field);
}
assert.match(sql, /FOR UPDATE OF r SKIP LOCKED/, 'Concurrent joins must not overfill lobbies');
assert.match(sql, /INSERT INTO public\.arena_rooms/, 'Unmatched users must receive their own room');
assert.match(sql, /IF v_count >= v_cap THEN UPDATE public\.arena_rooms/, 'Existing start-on-full behavior must remain');
assert.match(sql, /IF v_room IS NOT NULL THEN RETURN v_room/, 'Returning players must recover their existing arena');
assert.match(sql, /abs\(coalesce\(a_rating, 1000\)::bigint - coalesce\(b_rating, 1000\)::bigint\) <= 700/, 'Rating range guard');
assert.match(sql, /<= 3 \* greatest\(1, least\(coalesce\(a_hp/, 'HP ratio guard missing');
assert.match(sql, /<= 4 \* greatest\(1, least\(coalesce\(a_attack/, 'Attack ratio guard missing');
assert.match(sql, /<= 4 \* greatest\(1, least\(coalesce\(a_defense/, 'Defense ratio guard missing');
assert(!/UPDATE\s+public\.players/i.test(sql), 'Do not modify any player stats or inventories');
assert(!/DELETE\s+FROM\s+public\./i.test(sql), 'Never delete records as part of matching');
console.log('Arena matcher: human level/rating/power separation; safe bot fallback; existing session preserved.');


// Arena leaderboard NPCs must be the SAME opponents generated by arena_start_room.
const arenaSql = readFileSync('supabase/migrations/20261002195511_arena_live_battles.sql', 'utf8');
const roster = readFileSync('src/game/arenaWeeklyBots.ts', 'utf8');
const weeklyUI = readFileSync('src/components/arena/ArenaWeeklyBoard.tsx', 'utf8');
const pool = arenaSql.match(/v_names text\[\] := ARRAY\[([\s\S]*?)\];/);
assert(pool, 'Production Arena bot-name pool missing');
const canonicalNames = [...pool[1].matchAll(/'([^']+)'/g)].map(m => m[1]);
assert.equal(canonicalNames.length, 40, 'Arena source-of-truth changed: update the leaderboard roster deliberately');
// The weekly TOP uses the existing PvP naming style, but is curated
// separately from combat matchmaking to stay 25/25 without numeric aliases.
const blockNames = (constName) => {
  const start = roster.indexOf('const ' + constName + ' = [');
  assert(start >= 0, 'Missing bot name array ' + constName);
  const end = roster.indexOf('] as const;', start);
  assert(end > start, 'Unterminated bot name array ' + constName);
  return [...roster.slice(start, end).matchAll(/'([^']+)'/g)].map(x => x[1]);
};
const ruNames = blockNames('RUSSIAN_ARENA_BOT_NAMES');
const enNames = blockNames('ENGLISH_ARENA_BOT_NAMES');
assert.equal(ruNames.length, 25);
assert.equal(enNames.length, 25);
assert.equal(new Set([...ruNames, ...enNames]).size, 50);
assert(ruNames.every(x => canonicalNames.includes(x) && /^[А-Яа-яЁё]+$/.test(x)),
  'Existing Cyrillic PvP names must be curated without variants');
assert(enNames.every(x => /^[A-Za-z]+$/.test(x)), 'English Arena aliases must be Latin-only and digit-free');
assert(enNames.some(x => canonicalNames.includes(x)), 'Preserve existing English PvP bot names too');
assert.match(roster, /arenaBot: true/, 'Leaderboard entries must be distinguishable from people');
assert.match(roster, /const candidates: ArenaWeeklyDisplayPlayer\[\]/, 'Everyone must compete in one shared ranking');
assert.match(roster, /candidates\.sort\(\(a, b\) => b\.wins - a\.wins/, 'Weekly placements must follow victory totals');
assert.match(roster, /candidates\.slice\(0, 50\)/, 'Display must contain exactly top 50 scores');
assert.match(roster, /rank: index \+ 1/, 'Displayed ranks must run continuously from 1');
assert.doesNotMatch(roster, /rank <= 9|50 - Math\.max\(9, humans\.length\)/, 'Artificial NPC rank limits must not return');
assert.match(weeklyUI, /arenaWeeklyWithBots/, 'Weekly ranking should merge verified players with NPC placeholders');
assert.match(weeklyUI, /Боец арены: игровой бот/, 'NPC identity must be available on the actual leaderboard entry');
assert.match(weeklyUI, /Соперник арены/, 'NPC entry must have a concise label instead of the removed explanatory footer');
assert.doesNotMatch(weeklyUI, /Места 10–50 могут занимать боты арены/, 'Removed verbose NPC footer must not reappear');
assert.doesNotMatch(roster, /supabase\.(?:from|rpc)|update\(|insert\(|delete\(/i,
  'Leaderboard filler may never mutate authoritative PvP game state');
console.log('Weekly Arena TOP: 25 Cyrillic + 25 Latin unique names without numerical variants; real players and bots ranked by victories.');

