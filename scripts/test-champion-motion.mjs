import { test } from 'node:test';
import assert from 'node:assert/strict';
import { AUTO_SEQUENCE, CLIPS, REST, buildRigMarkup, sampleClip } from '../public/assets/territory/champion-preview/champion-motion.mjs';

test('all 2D combat clips have increasing timestamps and interpolated finite bones', () => {
  const jointNames = Object.keys(REST);
  assert.ok(Object.keys(CLIPS).length >= 18);
  for (const [name, clip] of Object.entries(CLIPS)) {
    assert.ok(clip.title && clip.duration > 300, `${name} has a label and duration`);
    assert.equal(clip.frames[0].at, 0, `${name} starts at t=0`);
    assert.equal(clip.frames.at(-1).at, 1, `${name} ends at t=1`);
    for (let index=1;index<clip.frames.length;index++) {
      assert.ok(clip.frames[index].at > clip.frames[index-1].at, `${name} frames increase`);
    }
    for (const frame of clip.frames) {
      for (const field of Object.keys(frame)) {
        if (field==='at') continue;
        assert.ok(jointNames.includes(field), `${name} uses a defined bone: ${field}`);
        assert.ok(Number.isFinite(frame[field]), `${name}.${field} is a finite number`);
      }
    }
    for (const t of [0,.07,.25,.5,.71,.95,1]) {
      const result=sampleClip(clip,t);
      for (const key of jointNames) assert.ok(Number.isFinite(result[key]), `${name}.${key} at ${t}`);
    }
  }
});

test('the autogenerated 2D rig has all 14 independent images and articulated joints', () => {
  const markup=buildRigMarkup();
  assert.equal((markup.match(/<image /g)||[]).length, 14);
  for (const bone of ['champion-back-knee','champion-front-knee','champion-shield-elbow','champion-shield-wrist','champion-axe-elbow','champion-axe-wrist','champion-torso','champion-head','champion-scarf']) {
    assert.ok(markup.includes(`id="${bone}"`), `rig contains ${bone}`);
  }
});

test('automatic showcase only references declared moves', () => {
  assert.ok(AUTO_SEQUENCE.length >= 12);
  for (const name of AUTO_SEQUENCE) assert.ok(CLIPS[name], `${name} exists`);
});
