import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const screen = readFileSync('src/components/ClanScreen.tsx', 'utf8');
const api = readFileSync('src/game/clanApi.ts', 'utf8');
const lang = readFileSync('src/game/i18n.tsx', 'utf8');
const snapshot = readFileSync('supabase/migrations/20261017_clans_functions_snapshot.sql', 'utf8');
const patch = readFileSync('supabase/patches/clan_creation_30_red_gems.sql', 'utf8');
const start = snapshot.indexOf('CREATE OR REPLACE FUNCTION public.clan_create(');
const end = snapshot.indexOf('CREATE OR REPLACE FUNCTION public.clan_decline_invite(', start);
assert(start >= 0 && end > start, 'clan_create function exists in server snapshot');
const fn = snapshot.slice(start, end);
assert.match(api, /CLAN_CREATION_RED_GEMS_COST = 30;/);
assert.match(screen, /redGems < CLAN_CREATION_RED_GEMS_COST/, 'disable purchase when funds are low');
assert.match(screen, /t\('clanYourRedGems'\)/, 'show actual player red diamond balance');
assert.match(screen, /clan_not_enough_red_gems/, 'map server insufficient funds error');
assert.doesNotMatch(screen, /gold < 100000|100 000 —/, 'no obsolete gold price in UI');
assert.match(lang, /Создать клан за 30 красных алмазов/);
assert.match(lang, /Create for 30 red diamonds/);
assert.match(fn, /redGems'\)::bigint < 30/, 'server checks 30 red gems');
assert.match(fn, /\{player,redGems\}/, 'server deducts red gems from saved wallet');
assert.match(fn, /::integer - 30\)/, 'deduct exact amount');
assert.match(fn, /clan_not_enough_red_gems/, 'server insufficient funds guard');
assert.match(fn, /FOR UPDATE/, 'serialize concurrent wallet transactions');
assert.match(fn, /p\.updated_at <> p_expected/, 'revision check prevents stale double-spends');
assert.match(fn, /clan_already_member/, 'cannot create a second clan');
assert.match(fn, /IF p\.level < 15/, 'retain existing level requirement');
assert.match(fn, /'spend', 0, 'create_30_red_gems'/, 'treasury log does not invent a gold payment');
assert.doesNotMatch(fn, /p\.gold - 100000|clan_not_enough_gold|-100000|100000/, 'no gold deduction');
assert(patch.includes(fn.trim()), 'standalone clan patch mirrors canonical function');
console.log('Clan creation cost: 30 red diamonds, exact atomic deduction, no gold spent — PASS');
