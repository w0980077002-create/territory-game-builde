const FEMALE_BOT_NAMES = new Set([
  'Хельга', 'Астрид', 'Фрейя', 'Лагерта', 'Сольвейг', 'Ингрид', 'Valkyr', 'Тордис',
]);

export type ArenaWeeklyDisplayPlayer = ArenaWeeklyPlayer & {
  /** Never treat visual bot scores as server-confirmed player victories. */
  arenaBot?: boolean;
};

export interface ArenaWeeklyDisplay {
  leaders: ArenaWeeklyDisplayPlayer[];
  displayRank: number | null;
  isDisplayRankVerified: boolean;
}

function stableHash(text: string): number {
  let result = 2166136261;
  for (let i = 0; i < text.length; i += 1) {
    result = Math.imul(result ^ text.charCodeAt(i), 16777619);
  }
  return result >>> 0;
}

/**
 * Place canonical arena bots only at 10..50 (the first nine slots are
 * exclusively server-confirmed players). Server-confirmed users compete
 * against the seasonal bot targets for the remaining positions.
 *
 * Bot scores rise gently as the week advances and never touch Supabase.
 * Use a fixed week start so all users see the same roster and scores.
 */
export function arenaWeeklyWithBots(
  verified: ArenaWeeklyStatus,
  now: number = Date.now(),
): ArenaWeeklyDisplay {
  const humans = verified.leaders
    .filter((p) => p && !p.player_id.startsWith('arena-npc:'))
    .slice()
    .sort((a, b) => a.rank - b.rank || b.wins - a.wins);
  const leaders: ArenaWeeklyDisplayPlayer[] = humans.filter((p) => p.rank <= 9)
    .map((p) => ({ ...p, arenaBot: false }));

  const start = Date.parse(verified.starts_at);
  const end = Date.parse(verified.ends_at);
  if (!Number.isFinite(start) || !Number.isFinite(end) || end <= start || now < start || now >= end) {
    return { leaders: humans, displayRank: verified.my_rank, isDisplayRankVerified: true };
  }

  const currentDay = Math.min(6, Math.floor((now - start) / 86_400_000));
  const week = verified.starts_at.slice(0, 10);
  // Fixed, attainable tournament targets, rising over a Sunday-Sunday season.
  let ceiling = 6 + currentDay * 3;
  const lastProtected = humans.find((p) => p.rank === 9);
  if (lastProtected) ceiling = Math.min(ceiling, Math.max(1, lastProtected.wins));
  ceiling = Math.max(1, ceiling);

  const bots: ArenaWeeklyDisplayPlayer[] = ARENA_PVP_BOT_NAMES.map((name, index) => {
    const seed = stableHash(week + ':' + name);
    const sequence = (index + seed % 41) % 41;
    const victories = Math.max(1, ceiling - Math.floor(sequence * ceiling / 41));
    const female = FEMALE_BOT_NAMES.has(name);
    return {
      player_id: 'arena-npc:' + name,
      display_name: name,
      level: 15 + (seed % 46),
      appearance: female ? (seed % 2 ? 'f1' : 'f2') : (seed % 2 ? 'm1' : 'm2'),
      wins: victories,
      rank: 0,
      arenaBot: true,
    };
  });

  // Fill only the vacant slots. Once 50 real players qualify, no NPCs remain.
  // Real players always win equal-score ties, so they can displace opponents.
  const vacancies = Math.max(0, 50 - Math.max(9, humans.length));
  const remaining = [
    ...humans.filter((p) => p.rank > 9).map((p) => ({ ...p, arenaBot: false })),
    ...bots.slice(0, vacancies),
  ];
  remaining.sort((a, b) => b.wins - a.wins
    || Number(Boolean(a.arenaBot)) - Number(Boolean(b.arenaBot))
    || (a.arenaBot && b.arenaBot ? stableHash(week + a.display_name) - stableHash(week + b.display_name) : a.rank - b.rank));

  let nextRank = 10;
  for (const item of remaining.slice(0, 41)) {
    leaders.push({ ...item, rank: nextRank++ });
  }
  const myPlayer = verified.my_rank == null ? null : humans.find((p) => p.rank === verified.my_rank);
  const displayedMe = myPlayer && leaders.find((p) => p.player_id === myPlayer.player_id);
  return {
    leaders,
    displayRank: displayedMe?.rank ?? null,
    isDisplayRankVerified: !!displayedMe && !displayedMe.arenaBot,
  };
}
