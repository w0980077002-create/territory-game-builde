export function localizeText(text: string, language: Language): string {
  return language === 'en' ? (contentEnglish[text] ?? text) : text;
}

interface LanguageContextValue { language: Language; setLanguage: (language: Language) => void; t: (key: string) => string; }
const LanguageContext = createContext<LanguageContextValue | null>(null);
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try { return localStorage.getItem('territory-language') === 'en' ? 'en' : 'ru'; } catch { return 'ru'; }
  });
  const setLanguage = (next: Language) => {
    setLanguageState(next);
    try { localStorage.setItem('territory-language', next); } catch { /* Some Telegram webviews may block storage. */ }
  };
  useEffect(() => { document.documentElement.lang = language; }, [language]);
  const value = useMemo<LanguageContextValue>(() => ({ language, setLanguage, t: (key) => dictionaries[language][key] ?? key }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error('useLanguage must be used inside LanguageProvider');
  return value;
}
