-- TERRITORY Game Hall: remove the DAILY gold payout cap, retain per-round
-- server-verified rewards, wallet CAS, ticket debit, session expiry and locks.
-- Pending gold stays bounded at 100000 until the player claims it.
-- No account balances or player records are reset or migrated.
BEGIN;
SET LOCAL lock_timeout = '3s';
SET LOCAL statement_timeout = '20s';

DO $hall_uncap$
DECLARE
  routine text;
  routine_oid oid;
  before_sql text;
  after_sql text;
  from_sql text;
  to_sql text;
BEGIN
  -- Stop rather than changing unrecognized production SQL.
  FOREACH routine IN ARRAY ARRAY[
    'public.territory_hall_finish_v1(uuid,integer)',
    'public.territory_hall_status_v1()',
    'public.territory_monopoly_v2(text,integer,uuid)'
  ] LOOP
    routine_oid := to_regprocedure(routine);
    IF routine_oid IS NULL THEN
      RAISE EXCEPTION 'Missing verified game function: %', routine;
    END IF;
    before_sql := pg_get_functiondef(routine_oid);
    after_sql := before_sql;

    IF routine LIKE '%territory_hall_finish_v1%' THEN
      from_sql := 'v_gold:=CASE WHEN v_win THEN least(s.gold_reward,greatest(0,1000-v_total_today)) ELSE 0 END;';
      to_sql := 'v_gold:=CASE WHEN v_win THEN least(s.gold_reward,greatest(0,100000-a.pending_gold)) ELSE 0 END;';
      IF position(from_sql IN after_sql) = 0 THEN RAISE EXCEPTION 'Hall gold guard changed: %',routine; END IF;
      after_sql := replace(after_sql,from_sql,to_sql);

      from_sql := 'daily_gold=v_total_today+v_gold,daily_day=v_day';
      to_sql := 'daily_gold=least(100000000,v_total_today+v_gold),daily_day=v_day';
      IF position(from_sql IN after_sql) = 0 THEN RAISE EXCEPTION 'Hall daily accounting changed'; END IF;
      after_sql := replace(after_sql,from_sql,to_sql);

      from_sql := '''daily_remaining'',greatest(0,1000-v_total_today-v_gold)';
      to_sql := '''daily_remaining'',greatest(0,100000-a.pending_gold-v_gold)';
      IF position(from_sql IN after_sql) = 0 THEN RAISE EXCEPTION 'Hall finish response changed'; END IF;
      after_sql := replace(after_sql,from_sql,to_sql);

    ELSIF routine LIKE '%territory_hall_status_v1%' THEN
      from_sql := '''daily_remaining'',greatest(0,1000-CASE WHEN a.daily_day=v_today THEN a.daily_gold ELSE 0 END)';
      to_sql := '''daily_remaining'',greatest(0,100000-a.pending_gold)';
      IF position(from_sql IN after_sql) = 0 THEN RAISE EXCEPTION 'Hall status response changed'; END IF;
      after_sql := replace(after_sql,from_sql,to_sql);

    ELSE
      -- Monopoly x10: still only rewards the result generated by the server.
      from_sql := ',1000-a.daily_gold,100000-a.pending_gold';
      to_sql := ',greatest(0,100000-a.pending_gold)';
      IF position(from_sql IN after_sql) = 0 THEN RAISE EXCEPTION 'Monopoly extra payout guard changed'; END IF;
      after_sql := replace(after_sql,from_sql,to_sql);

      from_sql := 'daily_gold=daily_gold+v_extra WHERE player_id=u';
      to_sql := 'daily_gold=least(100000000,daily_gold+v_extra) WHERE player_id=u';
      IF position(from_sql IN after_sql) = 0 THEN RAISE EXCEPTION 'Monopoly daily accounting changed'; END IF;
      after_sql := replace(after_sql,from_sql,to_sql);
    END IF;
    IF after_sql = before_sql THEN RAISE EXCEPTION 'No changes in %',routine; END IF;
    -- CREATE OR REPLACE keeps the existing function signature and privileges.
    EXECUTE after_sql;
  END LOOP;
END $hall_uncap$;

-- Preserve the bound on stored accounting values, raise it beyond ordinary
-- gameplay rather than silently capping rewards at 1000 each calendar day.
ALTER TABLE territory_private.hall_accounts_v1
  DROP CONSTRAINT hall_accounts_v1_daily_gold_check;
ALTER TABLE territory_private.hall_accounts_v1
  ADD CONSTRAINT hall_accounts_v1_daily_gold_check
  CHECK (daily_gold BETWEEN 0 AND 100000000);

COMMIT;
