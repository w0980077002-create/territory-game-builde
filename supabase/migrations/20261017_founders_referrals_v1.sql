-- TERRITORY referral season: server-only attribution, time-gated rewards.
-- Red diamond fragments are whole integer FIFTHS, not float redGems.
-- Sealed chests are private durable records; no gift contents until an event.
CREATE SCHEMA IF NOT EXISTS territory_private;

CREATE TABLE territory_private.referral_profiles_v1 (
 player_id uuid PRIMARY KEY REFERENCES public.players(id) ON DELETE CASCADE,
 code text NOT NULL UNIQUE DEFAULT substr(replace(gen_random_uuid()::text,'-',''),1,14),
 founder_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 CONSTRAINT referral_code_hex CHECK (code ~ '^[0-9a-f]{14}$')
);
CREATE TABLE territory_private.referral_invites_v1 (
 invited_id uuid PRIMARY KEY REFERENCES public.players(id) ON DELETE CASCADE,
 inviter_id uuid NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 qualified_at timestamptz,
 reward_claimed_at timestamptz,
 welcome_claimed_at timestamptz,
 CONSTRAINT referral_not_self CHECK(inviter_id <> invited_id)
);
CREATE INDEX referral_inviter_lookup_v1 ON territory_private.referral_invites_v1(inviter_id,qualified_at);
CREATE TABLE territory_private.referral_chests_v1 (
 invited_id uuid PRIMARY KEY REFERENCES territory_private.referral_invites_v1(invited_id) ON DELETE CASCADE,
 inviter_id uuid NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
 sealed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 opened_at timestamptz,
 CONSTRAINT chest_closed_for_beta CHECK(opened_at IS NULL)
);
CREATE TABLE territory_private.referral_claim_cursor_v1 (
 player_id uuid PRIMARY KEY REFERENCES public.players(id) ON DELETE CASCADE,
 red_paid integer NOT NULL DEFAULT 0 CHECK(red_paid>=0),
 claimed_friends integer NOT NULL DEFAULT 0 CHECK(claimed_friends>=0)
);
CREATE TABLE territory_private.referral_weekly_stones_v1 (
 player_id uuid NOT NULL REFERENCES public.players(id) ON DELETE CASCADE,
 week_start date NOT NULL,
 stones integer NOT NULL DEFAULT 0 CHECK(stones BETWEEN 0 AND 6),
 PRIMARY KEY(player_id,week_start)
);
REVOKE ALL ON ALL TABLES IN SCHEMA territory_private FROM PUBLIC,anon,authenticated;

-- Only the bot-auth server may attach an invite, and only when the invited
-- player was JUST created with Telegram identity. One permanent inviter.
CREATE OR REPLACE FUNCTION public.territory_referral_attach_v1(p_invited uuid,p_code text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path='pg_catalog'
AS $$
DECLARE owner_id uuid;
BEGIN
 IF p_invited IS NULL OR p_code !~ '^ref_[0-9a-f]{14}$' THEN RETURN false; END IF;
 SELECT p.player_id INTO owner_id FROM territory_private.referral_profiles_v1 p
 JOIN public.players u ON u.id=p.player_id AND u.telegram_id IS NOT NULL AND NOT u.banned
 WHERE p.code=substr(p_code,5);
 IF owner_id IS NULL OR owner_id=p_invited THEN RETURN false; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.players
  WHERE id=p_invited AND telegram_id IS NOT NULL AND NOT banned
    AND created_at >= clock_timestamp()-interval '20 minutes')
 THEN RETURN false; END IF;
 INSERT INTO territory_private.referral_invites_v1(invited_id,inviter_id)
 VALUES(p_invited,owner_id) ON CONFLICT(invited_id) DO NOTHING;
 RETURN EXISTS(SELECT 1 FROM territory_private.referral_invites_v1
   WHERE invited_id=p_invited AND inviter_id=owner_id);
END $$;
REVOKE ALL ON FUNCTION public.territory_referral_attach_v1(uuid,text) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.territory_referral_attach_v1(uuid,text) TO service_role;

-- A verified Telegram login (not a browser RPC) qualifies the invited friend.
-- auth_date is signed by Telegram; it must be FRESH (10min) for credit.
CREATE OR REPLACE FUNCTION public.territory_referral_qualify_v1(
 p_invited uuid,p_telegram_id bigint,p_auth_date bigint)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path='pg_catalog'
AS $$
DECLARE v_updated int;
BEGIN
 IF p_invited IS NULL OR p_telegram_id IS NULL OR p_auth_date IS NULL
  OR p_auth_date < extract(epoch from clock_timestamp()-interval '10 minutes')
  OR p_auth_date > extract(epoch from clock_timestamp()+interval '1 minute')
 THEN RETURN false; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.players
  WHERE id=p_invited AND telegram_id=p_telegram_id AND NOT banned)
 THEN RETURN false; END IF;
 UPDATE territory_private.referral_invites_v1 a
 SET qualified_at=clock_timestamp()
 WHERE a.invited_id=p_invited AND qualified_at IS NULL
   AND a.created_at<=clock_timestamp()-interval '24 hours'
   AND (a.created_at AT TIME ZONE 'UTC')::date
      < (clock_timestamp() AT TIME ZONE 'UTC')::date;
 GET DIAGNOSTICS v_updated=ROW_COUNT;
 INSERT INTO territory_private.referral_chests_v1(invited_id,inviter_id)
 SELECT invited_id,inviter_id FROM territory_private.referral_invites_v1
 WHERE invited_id=p_invited AND qualified_at IS NOT NULL
 ON CONFLICT(invited_id) DO NOTHING;
 RETURN v_updated>0;
END $$;
REVOKE ALL ON FUNCTION public.territory_referral_qualify_v1(uuid,bigint,bigint) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.territory_referral_qualify_v1(uuid,bigint,bigint) TO service_role;

-- Status only reads qualification; the client cannot confer it on itself.

-- No browser-supplied counts/levels/XP/attribution are considered.
CREATE OR REPLACE FUNCTION public.territory_referral_status_v1()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='pg_catalog'
AS $$
DECLARE v_uid uuid:=auth.uid(); v_code text; v_founder bigint;
 v_total int; v_active int; v_unclaimed int; v_chests int; v_paid int; v_red_paid int;
 v_welcome boolean; v_pending_red int;
BEGIN
 IF v_uid IS NULL THEN RAISE EXCEPTION 'referral_login_required'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.players WHERE id=v_uid AND telegram_id IS NOT NULL AND NOT banned)
 THEN RAISE EXCEPTION 'referral_verified_telegram_required'; END IF;
 -- Profile sequence is private, immutable and seeded for existing verified players.
 INSERT INTO territory_private.referral_profiles_v1(player_id)
 SELECT v_uid WHERE NOT EXISTS(
   SELECT 1 FROM territory_private.referral_profiles_v1 WHERE player_id=v_uid
 ) ON CONFLICT(player_id) DO NOTHING;
 SELECT code,founder_number INTO v_code,v_founder
 FROM territory_private.referral_profiles_v1 WHERE player_id=v_uid;
 SELECT count(*),count(*) FILTER(WHERE qualified_at IS NOT NULL),
   count(*) FILTER(WHERE qualified_at IS NOT NULL AND reward_claimed_at IS NULL)
 INTO v_total,v_active,v_unclaimed FROM territory_private.referral_invites_v1 WHERE inviter_id=v_uid;
 SELECT count(*) INTO v_chests FROM territory_private.referral_chests_v1 WHERE inviter_id=v_uid;
 SELECT coalesce(red_paid,0),coalesce(claimed_friends,0) INTO v_red_paid,v_paid
 FROM territory_private.referral_claim_cursor_v1 WHERE player_id=v_uid;
 v_red_paid:=coalesce(v_red_paid,0);
 v_paid:=coalesce(v_paid,0);
 v_pending_red:=greatest(0,v_active/5-v_red_paid);
 SELECT EXISTS (SELECT 1 FROM territory_private.referral_invites_v1
  WHERE invited_id=v_uid AND welcome_claimed_at IS NULL) INTO v_welcome;
 RETURN jsonb_build_object(
  'code',v_code,'founder_number',CASE WHEN v_founder<=300 THEN v_founder ELSE NULL END,
  'places_left',greatest(0,300-(SELECT count(*) FROM territory_private.referral_profiles_v1 WHERE founder_number<=300)),
  'registered',v_total,'qualified',v_active,'pending_claims',v_unclaimed,
  'red_fragments',v_active % 5,'red_pending',v_pending_red,
  'red_earned_tenths',v_active*2,
  'sealed_chests',v_chests,'welcome_pending',v_welcome,
  'rank',CASE WHEN v_active>=25 THEN 'ambassador'
       WHEN v_active>=10 THEN 'gold'
       WHEN v_active>=5 THEN 'silver'
       WHEN v_active>=3 THEN 'bronze' ELSE 'recruit' END);
END $$;
REVOKE ALL ON FUNCTION public.territory_referral_status_v1() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.territory_referral_status_v1() TO authenticated;

CREATE OR REPLACE FUNCTION public.territory_referral_claim_v1(p_expected timestamptz)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='pg_catalog'
AS $$
DECLARE v_uid uuid:=auth.uid(); p public.players%ROWTYPE;
 v_total int; v_unpaid int; v_cursor territory_private.referral_claim_cursor_v1%ROWTYPE;
 v_gold int:=0; v_gems int:=0; v_stones int:=0; v_mats int:=0; v_red int:=0;
 v_week date:=(date_trunc('week',clock_timestamp() AT TIME ZONE 'UTC'))::date;
 v_week_used int:=0; v_welcome boolean:=false; v_welcome_item jsonb;
 v_inv jsonb; v_state jsonb; v_valid int;
BEGIN
 IF v_uid IS NULL OR p_expected IS NULL THEN RAISE EXCEPTION 'referral_login_required'; END IF;
 SELECT * INTO p FROM public.players WHERE id=v_uid AND telegram_id IS NOT NULL AND NOT banned FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'referral_verified_telegram_required'; END IF;
 IF p.updated_at<>p_expected OR jsonb_typeof(p.game_state) IS DISTINCT FROM 'object'
   OR jsonb_typeof(p.game_state->'player') IS DISTINCT FROM 'object'
   OR jsonb_typeof(p.game_state->'inventory') IS DISTINCT FROM 'array'
 THEN RAISE EXCEPTION 'referral_reload_save'; END IF;
 INSERT INTO territory_private.referral_claim_cursor_v1(player_id) VALUES(v_uid)
 ON CONFLICT(player_id) DO NOTHING;
 SELECT * INTO v_cursor FROM territory_private.referral_claim_cursor_v1
 WHERE player_id=v_uid FOR UPDATE;
 SELECT count(*) INTO v_total FROM territory_private.referral_invites_v1
 WHERE inviter_id=v_uid AND qualified_at IS NOT NULL;
 SELECT count(*) INTO v_unpaid FROM territory_private.referral_invites_v1
 WHERE inviter_id=v_uid AND qualified_at IS NOT NULL AND reward_claimed_at IS NULL;
 SELECT EXISTS(SELECT 1 FROM territory_private.referral_invites_v1
 WHERE invited_id=v_uid AND welcome_claimed_at IS NULL) INTO v_welcome;
 IF v_unpaid=0 AND v_total/5<=v_cursor.red_paid AND NOT v_welcome
 THEN RAISE EXCEPTION 'referral_nothing_to_claim'; END IF;
 v_valid:=least(greatest(10-v_cursor.claimed_friends,0),v_unpaid);
 v_gold:=v_valid*1500; v_gems:=v_valid*10;v_mats:=v_valid*2;
 -- Founding milestones are credited exactly once, using the immutable cursor.
 IF v_cursor.claimed_friends<3 AND v_cursor.claimed_friends+v_unpaid>=3 THEN
   v_gold:=v_gold+2000;
 END IF;
 IF v_cursor.claimed_friends<5 AND v_cursor.claimed_friends+v_unpaid>=5 THEN
   v_gold:=v_gold+3000; v_gems:=v_gems+10;
 END IF;
 v_red:=greatest(0,v_total/5-v_cursor.red_paid);
 IF v_welcome THEN
  v_gold:=v_gold+600; v_stones:=3;
  -- A non-equipment starter gift, never two extra equipment stacks.
  v_welcome_item:=jsonb_build_object('id','ref_founder_welcome_elixir',
   'type','elixir','name','Эликсир силы','icon','💪','rarity','rare',
   'description','+10 к атаке на один бой','qty',2,
   'effect',jsonb_build_object('stat','attack','value',10,'duration','battle'));
  IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(p.game_state->'inventory') x
   WHERE x->>'id'='ref_founder_welcome_elixir')
  THEN v_inv:=p.game_state->'inventory'||jsonb_build_array(v_welcome_item);
  ELSE v_inv:=p.game_state->'inventory'; END IF;
 ELSE v_inv:=p.game_state->'inventory'; END IF;
 INSERT INTO territory_private.referral_weekly_stones_v1(player_id,week_start,stones)
 VALUES(v_uid,v_week,0) ON CONFLICT DO NOTHING;
 SELECT stones INTO v_week_used FROM territory_private.referral_weekly_stones_v1
 WHERE player_id=v_uid AND week_start=v_week FOR UPDATE;
 v_stones:=v_stones+least(v_valid,greatest(0,6-v_week_used));
 IF (p.game_state->'player'->>'gold') !~ '^[0-9]{1,10}$'
  OR (p.game_state->'player'->>'gems') !~ '^[0-9]{1,10}$'
  OR (p.game_state->'player'->>'redGems') !~ '^[0-9]{1,10}$'
  OR (p.game_state->>'forgeMaterials') !~ '^[0-9]{1,10}$'
  OR (p.game_state->>'battleStones') !~ '^[0-9]{1,10}$'
  OR p.gold <> (p.game_state->'player'->>'gold')::integer
  OR p.gems <> (p.game_state->'player'->>'gems')::integer
  OR p.forge_materials <> (p.game_state->>'forgeMaterials')::integer
 THEN RAISE EXCEPTION 'referral_invalid_wallet'; END IF;
 IF p.gold::bigint+v_gold>2147483647 OR p.gems::bigint+v_gems>2147483647
  OR (p.game_state->'player'->>'redGems')::bigint+v_red>2147483647
  OR p.forge_materials::bigint+v_mats>2147483647
  OR (p.game_state->>'battleStones')::bigint+v_stones>2147483647
 THEN RAISE EXCEPTION 'referral_wallet_limit'; END IF;
 v_state:=jsonb_set(p.game_state,'{player,gold}',to_jsonb(p.gold+v_gold));
 v_state:=jsonb_set(v_state,'{player,gems}',to_jsonb(p.gems+v_gems));
 v_state:=jsonb_set(v_state,'{player,redGems}',
   to_jsonb((p.game_state->'player'->>'redGems')::int+v_red));
 v_state:=jsonb_set(v_state,'{battleStones}',
   to_jsonb((p.game_state->>'battleStones')::int+v_stones));
 v_state:=jsonb_set(v_state,'{forgeMaterials}',to_jsonb(p.forge_materials+v_mats));
 v_state:=jsonb_set(v_state,'{inventory}',v_inv);
 UPDATE public.players SET game_state=v_state,gold=p.gold+v_gold,gems=p.gems+v_gems,
  forge_materials=p.forge_materials+v_mats WHERE id=v_uid RETURNING * INTO p;
 -- All award + ledger changes commit in one transaction, or none do.
 UPDATE territory_private.referral_invites_v1 SET reward_claimed_at=clock_timestamp()
 WHERE inviter_id=v_uid AND qualified_at IS NOT NULL AND reward_claimed_at IS NULL;
 IF v_welcome THEN UPDATE territory_private.referral_invites_v1
 SET welcome_claimed_at=clock_timestamp()
 WHERE invited_id=v_uid AND welcome_claimed_at IS NULL; END IF;
 UPDATE territory_private.referral_claim_cursor_v1
 SET red_paid=v_cursor.red_paid+v_red,claimed_friends=v_cursor.claimed_friends+v_unpaid
 WHERE player_id=v_uid;
 UPDATE territory_private.referral_weekly_stones_v1
 SET stones=stones+least(v_valid,greatest(0,6-v_week_used))
 WHERE player_id=v_uid AND week_start=v_week;
 RETURN jsonb_build_object('success',true,'gold',v_gold,'gems',v_gems,
  'stones',v_stones,'materials',v_mats,'red_gems',v_red,
  'welcome_elixirs',CASE WHEN v_welcome THEN 2 ELSE 0 END,
  'friends_claimed',v_unpaid,'updated_at',p.updated_at,'game_state',p.game_state,
  'wallet_gold',p.gold,'wallet_gems',p.gems);
END $$;
REVOKE ALL ON FUNCTION public.territory_referral_claim_v1(timestamptz) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.territory_referral_claim_v1(timestamptz) TO authenticated;

-- Seed original verified Telegram players in original signup order as founders.
-- No existing friend claims are fabricated, and no balances are changed.
INSERT INTO territory_private.referral_profiles_v1(player_id)
SELECT id FROM public.players WHERE telegram_id IS NOT NULL AND NOT banned
ORDER BY created_at,id ON CONFLICT(player_id) DO NOTHING;
